#!/usr/bin/env python3
"""
Damage Function Coefficient Consistency Tests
=============================================

Tests validating numerical consistency between the refactored damage function
implementation and the original DSCIM library.

This test suite ensures that the refactored damage function fitting produces
results that are structurally and numerically consistent with the original
DSCIM implementation. It compares damage function points, fitted coefficients,
and predictions against actual DSCIM output files.

Test Coverage:
    - Damage function points consistency (count, structure, values)
    - Fitted coefficients comparison with original DSCIM results
    - Prediction structure and numerical validation
    - Complete workflow consistency verification
    - Handling of data limitations and extrapolation differences

Methodology:
    Tests load actual DSCIM output files generated by the original implementation
    and compare them against results from the refactored code using the same
    input data. Comparisons account for known limitations such as different
    year ranges due to climate data availability.

Design Principles:
    - Direct comparison with actual DSCIM output files
    - Flexible comparison handling known implementation differences
    - Comprehensive structural and numerical validation
    - Clear reporting of consistency metrics and limitations
    - Robust handling of coordinate and dimension differences

Usage:
    These tests should be run to validate that the refactored damage function
    implementation maintains consistency with the original DSCIM methodology
    while providing improved modularity and testability.
"""

